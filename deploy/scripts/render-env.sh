#!/usr/bin/env bash
# Render the production env file from environment variables (CI secrets).
#
# The deploy workflow exports the secrets, then runs this on the VPS. Values are
# never echoed and the file is written with mode 600. It replaces the target
# atomically, so a failed render leaves the previous file intact.
#
#   JOB_DOMAIN=jobs.example.com CANDIDATE_DOMAIN=candidates.example.com \
#   FRONTEND_DOMAIN=app.example.com DJANGO_SECRET_KEY=... \
#   ./deploy/scripts/render-env.sh /opt/jobportal/.env
#
# Required: DJANGO_SECRET_KEY, INTERNAL_TOKEN, ADMIN_PASSWORD,
#           JOB_DB_PASSWORD, CANDIDATE_DB_PASSWORD,
#           JOB_JWT_SIGNING_KEY, JOB_JWT_PUBLIC_KEY,
#           CANDIDATE_JWT_SIGNING_KEY, CANDIDATE_JWT_PUBLIC_KEY,
#           JOB_DOMAIN, CANDIDATE_DOMAIN, FRONTEND_DOMAIN.
set -euo pipefail

TARGET="${1:-/opt/jobportal/.env}"

require() {
  local name="$1"
  if [[ -z "${!name:-}" ]]; then
    echo "render-env: missing required variable ${name}" >&2
    exit 1
  fi
}

for name in DJANGO_SECRET_KEY INTERNAL_TOKEN ADMIN_PASSWORD \
  JOB_DB_PASSWORD CANDIDATE_DB_PASSWORD \
  JOB_JWT_SIGNING_KEY JOB_JWT_PUBLIC_KEY \
  CANDIDATE_JWT_SIGNING_KEY CANDIDATE_JWT_PUBLIC_KEY \
  JOB_DOMAIN CANDIDATE_DOMAIN FRONTEND_DOMAIN; do
  require "${name}"
done

# Values are written shell-safe because deploy.sh sources this file. Secrets
# should not contain newlines; quote everything and escape single quotes.
quote() {
  local value="$1"
  printf "'%s'" "${value//\'/\'\\\'\'}"
}

JOB_PUBLIC_URL="${JOB_PUBLIC_URL:-https://${JOB_DOMAIN}}"
CANDIDATE_PUBLIC_URL="${CANDIDATE_PUBLIC_URL:-https://${CANDIDATE_DOMAIN}}"
FRONTEND_PUBLIC_URL="${FRONTEND_PUBLIC_URL:-https://${FRONTEND_DOMAIN}}"
ALLOWED_HOSTS="${ALLOWED_HOSTS:-${JOB_DOMAIN},${CANDIDATE_DOMAIN},${FRONTEND_DOMAIN},localhost,127.0.0.1}"

TMP="$(mktemp "${TARGET}.XXXXXX")"
trap 'rm -f "${TMP}"' EXIT
umask 077

HSTS_MAX_AGE="${SECURE_HSTS_SECONDS:-31536000}"
if [[ "${HSTS_MAX_AGE}" == "0" ]]; then
  HSTS_HEADER="max-age=0"
else
  HSTS_HEADER="max-age=${HSTS_MAX_AGE}; includeSubDomains; preload"
fi

{
  echo "# Generated by deploy/scripts/render-env.sh. Never commit this file."
  echo "COMPOSE_PROJECT_NAME=$(quote "${COMPOSE_PROJECT_NAME:-jobportal}")"
  echo "LOG_LEVEL=$(quote "${LOG_LEVEL:-INFO}")"
  echo "IMAGE_TAG=$(quote "${IMAGE_TAG:-latest}")"
  echo "JOB_IMAGE=$(quote "${JOB_IMAGE:-jobportal/job-service}")"
  echo "CANDIDATE_IMAGE=$(quote "${CANDIDATE_IMAGE:-jobportal/candidate-service}")"
  echo "FRONTEND_IMAGE=$(quote "${FRONTEND_IMAGE:-jobportal/frontend}")"
  echo "JOB_DOMAIN=$(quote "${JOB_DOMAIN}")"
  echo "CANDIDATE_DOMAIN=$(quote "${CANDIDATE_DOMAIN}")"
  echo "FRONTEND_DOMAIN=$(quote "${FRONTEND_DOMAIN}")"
  echo "JOB_PUBLIC_URL=$(quote "${JOB_PUBLIC_URL}")"
  echo "CANDIDATE_PUBLIC_URL=$(quote "${CANDIDATE_PUBLIC_URL}")"
  echo "FRONTEND_PUBLIC_URL=$(quote "${FRONTEND_PUBLIC_URL}")"
  echo "ALLOWED_HOSTS=$(quote "${ALLOWED_HOSTS}")"
  echo "SECURE_HSTS_SECONDS=$(quote "${HSTS_MAX_AGE}")"
  echo "HSTS_HEADER=$(quote "${HSTS_HEADER}")"
  echo "CADDY_TLS=$(quote "${CADDY_TLS:-${ACME_EMAIL:-}}")"
  echo "HTTP_PORT=$(quote "${HTTP_PORT:-80}")"
  echo "HTTPS_PORT=$(quote "${HTTPS_PORT:-443}")"
  echo "DJANGO_SECRET_KEY=$(quote "${DJANGO_SECRET_KEY}")"
  echo "INTERNAL_TOKEN=$(quote "${INTERNAL_TOKEN}")"
  echo "ADMIN_USERNAME=$(quote "${ADMIN_USERNAME:-admin}")"
  echo "ADMIN_PASSWORD=$(quote "${ADMIN_PASSWORD}")"
  echo "JOB_DB_USER=$(quote "${JOB_DB_USER:-jobportal}")"
  echo "JOB_DB_PASSWORD=$(quote "${JOB_DB_PASSWORD}")"
  echo "CANDIDATE_DB_USER=$(quote "${CANDIDATE_DB_USER:-jobportal}")"
  echo "CANDIDATE_DB_PASSWORD=$(quote "${CANDIDATE_DB_PASSWORD}")"
  echo "JOB_JWT_SIGNING_KEY=$(quote "${JOB_JWT_SIGNING_KEY}")"
  echo "JOB_JWT_PUBLIC_KEY=$(quote "${JOB_JWT_PUBLIC_KEY}")"
  echo "CANDIDATE_JWT_SIGNING_KEY=$(quote "${CANDIDATE_JWT_SIGNING_KEY}")"
  echo "CANDIDATE_JWT_PUBLIC_KEY=$(quote "${CANDIDATE_JWT_PUBLIC_KEY}")"
} >"${TMP}"

chmod 600 "${TMP}"
mv -f "${TMP}" "${TARGET}"
chown "${DEPLOY_USER:-$(id -un)}":"${DEPLOY_USER:-$(id -gn)}" "${TARGET}" 2>/dev/null || true
trap - EXIT

echo "render-env: wrote ${TARGET} (mode 600); values not printed"
